/**
 * ============================================================================
 * NEIRANDERTALTH: TIMELINE PARADOX — HISTORICAL RECORD (src/timeline/HistoricalRecord.js)
 * Генератор сатирических канонических глав учебника истории 3500 года.
 * ============================================================================
 */

export class HistoricalRecord {
    constructor() {
        this.stats = {
            totalKills: 0,
            totalHijacks: 0,
            totalEurekas: 0,
            temporalJumps: 0,
            highestWanted: 0
        };

        this.chapters = [
            {
                number: 1,
                title: 'Глава I. Появление Первопредка у Нефтяных Разломов',
                text: 'Священный Путешественник сошел в первобытные топи плейстоцена. Историки 3500 года единогласно признают: именно удары его костяной дубины сформировали зачатки этики и порядка.',
                quote: '«Тот, кто не уклонился от дубины, навек вошел в священный перегной цивилизации.»'
            }
        ];
    }

    recordKill(role, victimCount) {
        this.stats.totalKills += victimCount;
        if (this.stats.totalKills % 6 === 0) {
            this.addChapter(
                `Глава ${this.chapters.length + 1}. Великое Демографическое Умиротворение`,
                `Первопредок провел решительную санитарную реформу численности населения (${this.stats.totalKills} умиротворенных). В учебниках нео-мегаполиса этот день отмечается как «Праздник Свободного Жизненного Пространства».`,
                '«Меньше ртов у костра — больше битума в хранилищах.»'
            );
        }
    }

    recordHijack(vehicleName) {
        this.stats.totalHijacks++;
        this.addChapter(
            `Глава ${this.chapters.length + 1}. Освящение Скоростного Хода [${vehicleName}]`,
            `Первопредок лично испытал прочность ездового зверя/машины, сбросив прежнего возничего на мостовую во славу науки. Разлет свидетелей при таране был признан священным ритуалом разгона тьмы.`,
            '«И возопил пешеход под колесами, и было то пением во славу прогресса.»'
        );
    }

    recordEureka(text) {
        this.stats.totalEurekas++;
        this.addChapter(
            `Глава ${this.chapters.length + 1}. Грязное Озарение из Отбросов`,
            `Благодаря священной грязи и случайному озарению было открыто: «${text}». Академики будущего признали этот момент поворотным в истории квантового битума.`,
            '«Истина не в свитках, а на дне смоляного котла.»'
        );
    }

    recordJump(fromEpoch, toEpoch) {
        this.stats.temporalJumps++;
        this.addChapter(
            `Глава ${this.chapters.length + 1}. Прорыв Пространственно-Временной Ткани`,
            `Свершился хроноскачок из [${fromEpoch.name}] в [${toEpoch.name}]. Все грехи и преступления прошлого кристаллизовались в святые реликвии будущего.`,
            '«Время — это лишь пластилин в руках того, кто умеет угонять мамонтов.»'
        );
    }

    addChapter(title, text, quote) {
        this.chapters.push({
            number: this.chapters.length + 1,
            title,
            text,
            quote
        });
    }
}
